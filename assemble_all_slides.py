"""
assemble_all_slides.py
Merges L4, L5, and L6 datasets, applies safe Thai formatting, and outputs slides_data.js
"""
import json
import os
import re
from build_l4 import generate_l4_dataset
from build_l5 import generate_l5_dataset
from build_l6 import generate_l6_dataset

def safe_format_thai_text(text):
    if not text:
        return ""
    text = text.strip()
    
    # Normalize multiple inline spaces but preserve natural newlines
    lines = [re.sub(r'[ \t]+', ' ', line).strip() for line in text.split('\n')]
    text = '\n'.join(lines)
    
    # Check for numbered points: MUST have at least '1. ' and '2. '
    if re.search(r'(?::?\s+|^)1\.\s+', text) and re.search(r'\s+2\.\s+', text):
        match_first = re.search(r'(?::?\s+|^)1\.\s+', text)
        intro_part = text[:match_first.start()].strip()
        intro_part = re.sub(r'[:\s]+$', '', intro_part)
        if intro_part and not intro_part.endswith(':'):
            intro_part += ":"
            
        rest_part = text[match_first.start():].strip()
        # Split on numbered markers like '1. ', '2. ', '3. '
        items = re.split(r'(?:\s+|^)(\d+)\.\s+', rest_part)
        
        formatted_items = []
        for i in range(1, len(items), 2):
            num = items[i]
            content = items[i+1].strip()
            
            # Check for colon like 'Title: Body'
            colon_match = re.search(r'^([^:]{2,55}):\s*(.*)', content, re.DOTALL)
            if colon_match:
                title = colon_match.group(1).strip()
                body = colon_match.group(2).strip()
                formatted_items.append(f"• **{num}. {title}:** {body}")
            else:
                formatted_items.append(f"• **ข้อที่ {num}:** {content}")
                
        out = ""
        if intro_part:
            out += intro_part + "\n\n"
        out += "\n\n".join(formatted_items)
        return out
        
    return text

print("Assembling all slides from L4, L5, L6...")
l4 = generate_l4_dataset()
l5 = generate_l5_dataset()
l6 = generate_l6_dataset()

all_slides = l4 + l5 + l6
print(f"Total assembled slides: {len(all_slides)} (L4: {len(l4)}, L5: {len(l5)}, L6: {len(l6)})")

# Safely format Thai explanations
for s in all_slides:
    s['explanationTh'] = safe_format_thai_text(s.get('explanationTh', ''))

# Validation check
assert len(all_slides) == 302, f"Expected 302 slides, got {len(all_slides)}"

# Check that every image exists
missing_images = [s["image"] for s in all_slides if not os.path.exists(s["image"])]
if missing_images:
    print(f"WARNING: {len(missing_images)} missing images!")
else:
    print("ALL 302 slide images verified on disk!")

# Write to slides_data.js
js_content = f"// Autogenerated Slide Database for TMEC Specialty Chemicals & Gases (302 Slides Complete)\n"
js_content += f"// Lectures: L4 (133 slides), L5 (105 slides), L6 (64 slides)\n"
js_content += f"window.ALL_SLIDES = {json.dumps(all_slides, ensure_ascii=False, indent=2)};\n"

with open('slides_data.js', 'w', encoding='utf-8') as f:
    f.write(js_content)

print(f"Wrote slides_data.js successfully. File size: {len(js_content)/(1024):.1f} KB")
