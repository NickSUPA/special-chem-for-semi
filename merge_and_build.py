# -*- coding: utf-8 -*-
"""
merge_and_build.py
Merges cache_l4.json, cache_l5.json, cache_l6.json into slides_data.js
Validates that all 302 slides are present and have non-generic detailed explanations.
"""

import os
import json

LECTURE_CONFIGS = [
    {
        "code": "L4",
        "title": "Lecture 4: Specialty Chemicals & Gases for Semiconductor Fabrication",
        "titleTh": "บทที่ 1 & 2: สารเคมีและก๊าซพิเศษในกระบวนการผลิตอุปกรณ์สารกึ่งตัวนำ (Facilities, UPW, Gases, Etch)",
        "total": 133
    },
    {
        "code": "L5",
        "title": "Lecture 5: Specialty Gases and Chemicals for Lithography Process",
        "titleTh": "บทที่ 3: ก๊าซและสารเคมีพิเศษสำหรับกระบวนการโฟโตลิโทกราฟี (Photoresists, DUV, EUV, Track)",
        "total": 105
    },
    {
        "code": "L6",
        "title": "Lecture 6: CMP Chemicals (Chemical Mechanical Planarization)",
        "titleTh": "บทที่ 4: สารเคมีสำหรับกระบวนการขัดผิวเชิงกลและเคมี (CMP Slurries, Post-CMP Cleaning)",
        "total": 64
    }
]

def main():
    combined_cache = {}
    
    # Load master cache if present
    if os.path.exists("ai_slides_cache.json"):
        with open("ai_slides_cache.json", "r", encoding="utf-8") as f:
            combined_cache.update(json.load(f))
            
    # Load lecture caches
    for code in ["l4", "l5", "l6"]:
        cfile = f"cache_{code}.json"
        if os.path.exists(cfile):
            with open(cfile, "r", encoding="utf-8") as f:
                lec_data = json.load(f)
                combined_cache.update(lec_data)
                print(f"Loaded {len(lec_data)} from {cfile}")

    print(f"Total entries in combined cache: {len(combined_cache)}")
    
    all_slides = []
    missing_slides = []
    generic_slides = []
    
    for cfg in LECTURE_CONFIGS:
        code = cfg["code"]
        total = cfg["total"]
        for p in range(1, total + 1):
            sid = f"{code}-P{p:03d}"
            image_path = f"images/{code}_page_{p}.png"
            
            if sid not in combined_cache:
                missing_slides.append(sid)
                continue
                
            c = combined_cache[sid]
            exp = c.get("explanationTh", "").strip()
            if len(exp) < 100 or "สไลด์นี้อธิบายเนื้อหาหัวข้อ" in exp:
                generic_slides.append(sid)
                
            slide_obj = {
                "id": sid,
                "lecture": code,
                "lectureTitle": cfg["title"],
                "lectureTitleTh": cfg["titleTh"],
                "page": p,
                "totalPages": total,
                "titleEn": c.get("titleEn", sid),
                "titleTh": c.get("titleTh", sid),
                "category": c.get("category", "Semiconductor Manufacturing"),
                "categoryTh": c.get("categoryTh", "การผลิตสารกึ่งตัวนำ"),
                "image": image_path,
                "rawText": "",
                "summaryTh": c.get("summaryTh", ""),
                "explanationTh": exp,
                "keyPoints": c.get("keyPoints", []),
                "formula": c.get("formula", ""),
                "examTip": c.get("examTip", "")
            }
            all_slides.append(slide_obj)
            
    print(f"Assembled {len(all_slides)} / 302 slides.")
    print(f"Missing slides count: {len(missing_slides)}: {missing_slides[:10]}")
    print(f"Generic / short slides count: {len(generic_slides)}: {generic_slides[:10]}")
    
    # Save master cache
    with open("ai_slides_cache.json", "w", encoding="utf-8") as f:
        json.dump(combined_cache, f, ensure_ascii=False, indent=2)
        
    # Write slides_data.js
    js_content = f"// Autogenerated Slide Database for TMEC Specialty Chemicals & Gases (302 Slides AI-Generated Complete)\n"
    js_content += f"// Lectures: L4 (133 slides), L5 (105 slides), L6 (64 slides)\n"
    js_content += f"window.ALL_SLIDES = {json.dumps(all_slides, ensure_ascii=False, indent=2)};\n"
    
    with open("slides_data.js", "w", encoding="utf-8") as f:
        f.write(js_content)
        
    print(f"Successfully updated slides_data.js! File size: {len(js_content)/1024:.1f} KB")

if __name__ == "__main__":
    main()
